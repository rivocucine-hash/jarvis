const CMD_START = /^(ανοιξε|ανοιξ|βαλε|βαλ|κανε|καν|ξεκινα|ξεκινησε|αρχισε|παιξε|δειξε|δειξ|πεσ|πειτε|θελω|θα ηθελα|παμε|παμε για|τρεξε|φερε|δωσε|ετοιμασε|ενεργοποιησε|μπορεισ να|μπορειτε να|εχω|εχουμε|τι εχω|τι εχουμε|ποια|ποιεσ|ποσα|πωσ ειναι|πωσ πανε|πωσ παει|ωρα για|χρειαζομαι|πρεπει να)( |$)/;
const KNOWLEDGE_Q = /^(τι ειναι|τι σημαινει|γιατι|ποιοσ ειναι|ποια ειναι η|ποτε εγινε|πωσ λειτουργει|πωσ δουλευει|εξηγησε|ποιοσ εφτιαξε|ποιοσ ανακαλυψε|απο που)/;

function understand(n) {
  if (!n || KNOWLEDGE_Q.test(n)) return null;
  const words = n.split(' ').length;
  if (!CMD_START.test(n) && words > 4) return null;
  let best = null, bestScore = 0;
  for (const u of UNDERSTAND) {
    let s = 0;
    for (const k of u.k) if (n.includes(k)) s += (u.w || 1) + k.length / 20;
    if (s > bestScore) { bestScore = s; best = u; }
  }
  return best ? best.cmd : null;
}
